/**
 * Emits public/tesseract/lang/langdata.js — the Tesseract language data as a
 * JavaScript module of base64 strings.
 *
 *   node scripts/inline-ocr-lang.mjs
 *
 * Normally the app fetches `<lang>.traineddata.gz` from public/. Some static
 * hosts only serve a fixed set of file types and will not hand out a `.gz`,
 * which leaves OCR unable to start. Shipping the same bytes inside a real .js
 * module works anywhere a script does, at the cost of ~33% for base64.
 *
 * Opt in at build time with VITE_OCR_INLINE_LANG=1; see src/lib/ocr.ts.
 */
import { readFileSync, mkdirSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const LANGS = ["tha", "eng"];

const entries = LANGS.map((lang) => {
  const gz = readFileSync(
    join(root, "node_modules", "@tesseract.js-data", lang, "4.0.0_best_int", `${lang}.traineddata.gz`),
  );
  return `  ${lang}: "${gz.toString("base64")}",`;
});

const outDir = join(root, "public", "tesseract", "lang");
mkdirSync(outDir, { recursive: true });

const body = `// Generated by scripts/inline-ocr-lang.mjs — do not edit.
// Gzipped Tesseract language data, base64-encoded. Tesseract detects the gzip
// magic bytes and inflates it itself, so these go in exactly as they are.
export const LANGDATA = {
${entries.join("\n")}
};
`;

const out = join(outDir, "langdata.js");
writeFileSync(out, body);
console.log(`inline lang data: ${(body.length / 1024 / 1024).toFixed(1)} MB -> ${out}`);
